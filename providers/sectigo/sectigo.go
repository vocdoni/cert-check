// Package sectigo provides the Sectigo qualified citizen certificate type.
// Pass its provider to certcheck.NewHandler.
package sectigo

import (
	certcheck "github.com/vocdoni/cert-check"
	"github.com/vocdoni/cert-check/internal/engine"
	"github.com/vocdoni/cert-check/internal/profiles"
)

// New returns the Sectigo Ciudadano provider: qualified natural person
// (citizen) certificates not held on a qualified signature creation device
// (profile sectigo-citizen-local).
// opts are certcheck options. If no pinned anchor is valid at construction
// the provider is inert (no CAs) and certcheck.NewHandler rejects it.
func New(opts ...certcheck.Option) certcheck.Provider {
	return engine.FromOptions(profiles.Sectigo(), opts...)
}
